import { theme, type ThemeConfig } from 'antd';
import { UI_SCALE, UI_TYPE, type ThemeCard } from './cards';

function rgba(hex: string, alpha: number) {
  const [r, g, b] = [1, 3, 5].map(i => parseInt(hex.slice(i, i + 2), 16));
  return `rgba(${r}, ${g}, ${b}, ${alpha})`;
}

/**
 * `root` serves ordinary pages; `canon` keeps the tighter line height and list table styling
 * that the shell chrome and configured component frames already use.
 */
export function buildAntTheme(card: ThemeCard, variant: 'root' | 'canon' = 'root'): ThemeConfig {
  const p = card.palette;
  const r = UI_SCALE.radius;
  const c = UI_SCALE.control;
  const f = UI_SCALE.font;
  const t = UI_TYPE.role;
  const canon = variant === 'canon';
  return {
    algorithm: card.dark ? theme.darkAlgorithm : theme.defaultAlgorithm,
    token: {
      colorPrimary: p.accent,
      colorPrimaryHover: p.accentHover,
      colorPrimaryActive: p.accentActive,
      colorLink: p.accent,
      colorLinkHover: p.accentHover,
      colorLinkActive: p.accentActive,
      colorInfo: p.info,
      colorSuccess: p.success,
      colorWarning: p.warning,
      colorError: p.danger,
      colorSuccessBg: p.successBg,
      colorSuccessBorder: p.successBorder,
      colorWarningBg: p.warningBg,
      colorWarningBorder: p.warningBorder,
      colorErrorBg: p.dangerBg,
      colorErrorBorder: p.dangerBorder,
      colorInfoBg: p.infoBg,
      colorInfoBorder: p.infoBorder,
      colorTextBase: p.text,
      colorText: p.text,
      colorTextSecondary: p.muted,
      colorTextTertiary: p.muted,
      colorTextQuaternary: p.disabled,
      colorTextPlaceholder: p.muted,
      colorTextDisabled: p.disabled,
      colorTextLightSolid: p.accentText,
      ...(card.dark ? { colorBgBase: p.canvas } : {}),
      colorBgLayout: p.canvas,
      colorBgContainer: p.surface,
      colorBgElevated: p.surface,
      colorFillAlter: p.sunken,
      colorBorder: p.border,
      colorBorderSecondary: canon ? p.borderSoft : p.border,
      colorSplit: p.borderSoft,
      controlItemBgHover: p.hover,
      controlItemBgActive: p.selected,
      controlItemBgActiveHover: p.selected,
      controlOutline: rgba(p.focus, 0.2),
      controlHeight: c.middle,
      controlHeightSM: c.small,
      controlHeightLG: c.large,
      borderRadius: r.control,
      borderRadiusSM: r.tag,
      borderRadiusXS: r.tag,
      borderRadiusLG: r.panel,
      boxShadow: p.shadowPopover,
      boxShadowSecondary: p.shadowPopover,
      fontFamily: UI_TYPE.family.sans,
      fontFamilyCode: UI_TYPE.family.mono,
      fontSize: t.body.size,
      fontSizeSM: t.caption.size,
      fontSizeLG: t.section.size,
      fontSizeXL: t.heading.size,
      fontSizeHeading3: f.title,
      fontSizeHeading4: f.section,
      fontSizeHeading5: f.body,
      fontWeightStrong: UI_TYPE.weight.strong,
      lineHeight: canon ? t.control.line / t.body.size : t.body.line / t.body.size,
      lineHeightSM: t.caption.line / t.caption.size,
      lineHeightLG: t.section.line / t.section.size,
    },
    components: {
      Button: {
        fontWeight: 500,
        defaultColor: p.text,
        defaultBg: p.surface,
        defaultBorderColor: p.border,
        defaultHoverBg: p.hover,
        defaultHoverColor: p.text,
        defaultHoverBorderColor: p.borderStrong,
        defaultActiveBg: p.sunken,
        defaultActiveColor: p.text,
        defaultActiveBorderColor: p.borderStrong,
        primaryColor: p.accentText,
        defaultShadow: 'none',
        primaryShadow: 'none',
        dangerShadow: 'none',
      },
      Card: { borderRadiusLG: r.panel, paddingLG: 20 },
      Modal: {
        borderRadiusLG: r.overlay,
        headerBg: p.surface,
        contentBg: p.surface,
        footerBg: p.surface,
        titleColor: p.text,
        titleFontSize: f.section,
        boxShadow: p.shadowModal,
      },
      Drawer: { footerPaddingBlock: 16, footerPaddingInline: 24 },
      Form: { labelColor: p.text, labelFontSize: 13, itemMarginBottom: 16, verticalLabelPadding: '0 0 8px' },
      Select: {
        optionSelectedBg: p.selected,
        optionSelectedColor: p.text,
        optionSelectedFontWeight: 600,
        optionActiveBg: p.hover,
        optionPadding: '8px 12px',
        multipleItemBg: p.hover,
        multipleItemBorderColor: p.border,
      },
      Dropdown: { borderRadiusLG: r.panel, paddingBlock: 6 },
      Tabs: {
        itemColor: p.muted,
        itemSelectedColor: canon ? p.accent : p.text,
        itemHoverColor: p.text,
        itemActiveColor: p.text,
        inkBarColor: p.accent,
        cardBg: p.sunken,
      },
      Tag: { defaultBg: p.sunken, defaultColor: p.muted },
      Segmented: { trackBg: p.sunken, itemSelectedBg: p.surface, itemColor: p.muted, itemHoverColor: p.text, itemSelectedColor: p.text },
      Alert: { defaultPadding: '12px 16px', withDescriptionPadding: '16px', withDescriptionIconSize: 20 },
      Message: { contentBg: p.surface, contentPadding: '12px 16px' },
      Notification: { colorBgElevated: p.surface, borderRadiusLG: r.panel },
      Table: canon ? {
        headerBg: p.sunken,
        headerColor: p.muted,
        headerSplitColor: 'transparent',
        rowHoverBg: p.hover,
        rowSelectedBg: p.selectedSoft,
        rowSelectedHoverBg: p.selected,
        borderColor: p.borderSoft,
        cellPaddingBlock: 12,
        cellPaddingInline: 12,
      } : {
        cellFontSize: f.body,
        cellFontSizeMD: f.compact,
        cellFontSizeSM: f.compact,
        headerBg: p.sunken,
        headerColor: p.text,
        rowHoverBg: p.hover,
        rowSelectedBg: p.selected,
        rowSelectedHoverBg: p.selected,
        borderColor: p.border,
        headerBorderRadius: r.panel,
        headerSortHoverBg: p.hover,
        headerSortActiveBg: p.selected,
        bodySortBg: p.selectedSoft,
      },
      Menu: {
        itemBorderRadius: r.control,
        itemHeight: 36,
        itemColor: p.muted,
        itemHoverColor: p.text,
        subMenuItemBg: p.surface,
        popupBg: p.surface,
        groupTitleColor: p.accent,
        itemSelectedBg: p.selected,
        itemSelectedColor: p.accent,
        itemHoverBg: p.hover,
      },
    },
  };
}
